/* Look up the 2-bit width code for a code point in U+0000..U+10FFFF. */
static int haskeline_width_code(int ucs)
{
  unsigned int page;
  unsigned int offset;
  unsigned char packed;

  page = (unsigned int)ucs >> 8;
  offset = (unsigned int)ucs & 0xff;
  packed = haskeline_width_pages[haskeline_width_page_index[page]][offset >> 2];
  return (packed >> ((offset & 3) * 2)) & 3;
}

static int haskeline_width_for(int ucs, int cjk)
{
  int w;

  if (ucs == 0)
    return 0;
  if (ucs < 32 || (ucs >= 0x7f && ucs < 0xa0))
    return -1;
  if (ucs < 0 || ucs > 0x10ffff)
    return 1;

  w = haskeline_width_code(ucs);
  if (w == 3)
    return cjk ? 2 : 1;
  return w;
}

int haskeline_mk_wcwidth(int ucs)
{
  return haskeline_width_for(ucs, 0);
}

/*
 * The following functions are the same as mk_wcwidth() and
 * mk_wcswidth(), except that spacing characters in the East Asian
 * Ambiguous (A) category as defined in Unicode Technical Report #11
 * have a column width of 2. This variant might be useful for users of
 * CJK legacy encodings who want to migrate to UCS without changing
 * the traditional terminal character-width behaviour. It is not
 * otherwise recommended for general use.
 */
int haskeline_mk_wcwidth_cjk(wchar_t ucs)
{
  return haskeline_width_for((int)ucs, 1);
}

int haskeline_mk_wcswidth(const wchar_t *pwcs, size_t n)
{
  int w, width = 0;

  for (;*pwcs && n-- > 0; pwcs++)
    if ((w = haskeline_mk_wcwidth(*pwcs)) < 0)
      return -1;
    else
      width += w;

  return width;
}


int haskeline_mk_wcswidth_cjk(const wchar_t *pwcs, size_t n)
{
  int w, width = 0;

  for (;*pwcs && n-- > 0; pwcs++)
    if ((w = haskeline_mk_wcwidth_cjk(*pwcs)) < 0)
      return -1;
    else
      width += w;

  return width;
}
