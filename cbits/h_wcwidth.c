/*
 * This is an implementation of wcwidth() and wcswidth() (defined in
 * IEEE Std 1002.1-2001) for Unicode.
 *
 * http://www.opengroup.org/onlinepubs/007904975/functions/wcwidth.html
 * http://www.opengroup.org/onlinepubs/007904975/functions/wcswidth.html
 *
 * In fixed-width output devices, Latin characters all occupy a single
 * "cell" position of equal width, whereas ideographic CJK characters
 * occupy two such cells. Interoperability between terminal-line
 * applications and (teletype-style) character terminals using the
 * UTF-8 encoding requires agreement on which character should advance
 * the cursor by how many cell positions. No established formal
 * standards exist at present on which Unicode character shall occupy
 * how many cell positions on character terminals. These routines are
 * a first attempt of defining such behavior based on simple rules
 * applied to data provided by the Unicode Consortium.
 *
 * For some graphical characters, the Unicode standard explicitly
 * defines a character-cell width via the definition of the East Asian
 * FullWidth (F), Wide (W), Half-width (H), and Narrow (Na) classes.
 * In all these cases, there is no ambiguity about which width a
 * terminal shall use. For characters in the East Asian Ambiguous (A)
 * class, the width choice depends purely on a preference of backward
 * compatibility with either historic CJK or Western practice.
 * Choosing single-width for these characters is easy to justify as
 * the appropriate long-term solution, as the CJK practice of
 * displaying these characters as double-width comes from historic
 * implementation simplicity (8-bit encoded characters were displayed
 * single-width and 16-bit ones double-width, even for Greek,
 * Cyrillic, etc.) and not any typographic considerations.
 *
 * Much less clear is the choice of width for the Not East Asian
 * (Neutral) class. Existing practice does not dictate a width for any
 * of these characters. It would nevertheless make sense
 * typographically to allocate two character cells to characters such
 * as for instance EM SPACE or VOLUME INTEGRAL, which cannot be
 * represented adequately with a single-width glyph. The following
 * routines at present merely assign a single-cell width to all
 * neutral characters, in the interest of simplicity. This is not
 * entirely satisfactory and should be reconsidered before
 * establishing a formal standard in this area. At the moment, the
 * decision which Not East Asian (Neutral) characters should be
 * represented by double-width glyphs cannot yet be answered by
 * applying a simple rule from the Unicode database content. Setting
 * up a proper standard for the behavior of UTF-8 character terminals
 * will require a careful analysis not only of each Unicode character,
 * but also of each presentation form, something the author of these
 * routines has avoided to do so far.
 *
 * http://www.unicode.org/unicode/reports/tr11/
 *
 * Markus Kuhn -- 2007-05-26 (Unicode 5.0)
 * http://www.cl.cam.ac.uk/~mgk25/ucs/wcwidth.c
 *
 * wcwidth tables
 * ==============
 *
 * Generated from the Unicode Character Database (UCD), Unicode 18.0.0.
 * Do not edit the tables below by hand.
 *
 * Source data
 * -----------
 *
 *   UnicodeData.txt
 *     https://www.unicode.org/Public/18.0.0/ucd/UnicodeData.txt
 *     SHA-256: 0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950
 *   EastAsianWidth.txt
 *     https://www.unicode.org/Public/18.0.0/ucd/EastAsianWidth.txt
 *     SHA-256: a0cf29eacd00cfcaec4381c6b7c281685f18dbb4e7ff82b4076ccb342ca839aa
 *
 * Width rules
 * -----------
 *
 *   zero width
 *     (Mn | Me | Cf from field 3 of UnicodeData.txt)
 *     - U+00AD
 *     + U+1160-U+11FF
 *     + U+D7B0-U+D7C6
 *     + U+D7CB-U+D7FB
 *     The Hangul Jamo ranges are a wcwidth convention, not a Unicode
 *     general category.
 *
 *   wide
 *     (W | F from EastAsianWidth.txt)
 *
 *   ambiguous (CJK variant)
 *     (A from EastAsianWidth.txt)
 *     - (Mn | Me | Cf from UnicodeData.txt)
 *
 * Storage
 * -------
 *
 * The range tables of the origin implementation by Markus Kuhn have been 
 * replaced by a page-deduplicated lookup table. Unicode is split into
 * 256-code-point pages; each page stores four 2-bit width codes 
 * per byte (64 bytes per page).  Identical pages are stored once, 
 * and a 4352-entry index maps a Unicode page to its
 * stored page.  With Unicode 18.0.0 there are 116 unique pages:
 *
 *   116 * 64 + 4352 = 11776 bytes
 *
 * Lookup order
 * ------------
 *
 * Control characters are tested first, then the packed width table.
 * U+302A-U+302D, U+3099-U+309A and U+16FE4 occur in both the zero-width
 * and wide classes, so they must return 0.  U+00AD is not zero width.
 *
 * Verification
 * ------------
 *
 * Compare every code point in U+0000..U+10FFFF against the rules
 * above, with NUL -> 0, C0/C1/DEL -> -1, and the CJK variant mapping
 * ambiguous -> 2.  Also compile as C89 and run `cabal test`.
 *
 * Revision history
 * ----------------
 *
 *   2026-10-25  Unicode 18.0.0  soiamsoNG <83182235@qq.com>
 *               Co-author: DeepSeek V4.1 Flash <noreply@deepseek.com>
 *               Convert and Regenerated to the page tables from Unicode 18.0.0.
 *
 *   2007-05-26  Unicode 5.0     Markus Kuhn
 *               Original wcwidth implementation.
 *
 * Permission to use, copy, modify, and distribute this software
 * for any purpose and without fee is hereby granted. The author
 * disclaims all warranties with regard to this software.
 *
 */

